using ReactApp2.Server.Models.Interfaces;
using System.ComponentModel.DataAnnotations;

namespace ReactApp2.Server.Models
{
    // Checklist class represents a collection of related tasks that can be checked on/off
    public class Checklist: ISeries<WorkItem>
    {   
        [Required]
        public int Id { get; set; }
        [Required]
        [StringLength(200, MinimumLength = 1)]
        public string? Name { get; set; }
        [StringLength(500)]
        public string? Description { get; set; }
        public List<WorkItem>? Items { get; set; }
        public bool IsComplete { get; set; } = false;
        public bool IsDeleted { get; set; } = false;

        public DateTime? DeletedAt { get; set; }
    }

    // Model for creating a new checklist, id will be generated by the database, this is DTO (Data Transfer Object)
    public class  CreateChecklist: IIdentifiable
    {
        [Required]
        public int Id { get; set; }
        [Required]
        [StringLength(200, MinimumLength = 1)]
        public string? Name { get; set; }
        [StringLength(500)]
        public string? Description { get; set; }
    }
}
