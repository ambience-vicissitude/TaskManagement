using ReactApp2.Server.Models.Interfaces;
using System.ComponentModel.DataAnnotations;

namespace ReactApp2.Server.Models
{
    /// <summary>
    /// Checklist class represents a collection of related 'work items' that can be checked on/off
    /// </summary>
    public class Checklist: ISeries<WorkItem>
    {   
        /// <summary>
        /// Identifier
        /// </summary>
        [Required]
        public int Id { get; set; }
        
        /// <summary>
        /// Name of the checklist
        /// </summary>
        [Required]
        [StringLength(200, MinimumLength = 1)]
        public string? Name { get; set; }
        
        /// <summary>
        /// Short description about the checklist
        /// </summary>
        [StringLength(500)]
        public string? Description { get; set; }
        
        /// <summary>
        /// Collection of work items assigned to this checklist
        /// Can be null or empty if no items are assigned yet
        /// 
        /// Any unique work item can belong to only one checklist at a time or none at all
        /// </summary>
        public List<WorkItem>? Items { get; set; }
        
        /// <summary>
        /// Is the checklist 'done' / completed
        /// </summary>
        public bool IsComplete { get; set; } = false;

        /// <summary>
        /// Is the checklist soft deleted
        /// </summary>
        /// <remarks>
        /// IsDeleted could be redundant as DeletedAt != null could imply deletion, IsDeleted is more explicit and can simplify queries
        /// but for a small app and no code review done, we can keep it for now, risk the possibility of inconsistency
        /// </remarks>
        public bool IsDeleted { get; set; } = false;
        
        /// <summary>
        /// The datetime for when the checklist was soft deleted, null if not deleted
        /// 
        /// Used by the cleanup services to permanently delete after a configured set number of days
        /// </summary>
        public DateTime? DeletedAt { get; set; }
    }

    /// <summary>
    /// DTO (Data Transfer Object) for creating a new checklist, id will be generated by the database
    /// 
    /// Used for api layer validation
    /// </summary>
    public class  CreateChecklist: IIdentifiable
    {
        /// <summary>
        /// Identifier
        /// </summary>
        [Required]
        public int Id { get; set; }
        
        /// <summary>
        /// Name of the checklist
        /// </summary>
        [Required]
        [StringLength(200, MinimumLength = 1)]
        public string? Name { get; set; }

        /// <summary>
        /// Short description about the checklist
        /// </summary>
        [StringLength(500)]
        public string? Description { get; set; }
    }
}
