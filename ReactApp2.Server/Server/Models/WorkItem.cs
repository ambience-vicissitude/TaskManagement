using ReactApp2.Server.Models.Interfaces;
using System.ComponentModel.DataAnnotations;

namespace ReactApp2.Server.Models
{
    public class WorkItem : IIdentifiable
    {
        [Required]
        public int Id { get; set; }
        [Required]
        [StringLength(200, MinimumLength = 1)]
        public string? Name { get; set; }
        [StringLength(500)]
        public string? Description { get; set; }

        // Can be extended to support time zones in future, include start time if needed, duration, etc.
        public DateTime? DueDate { get; set; }

        // Can be extended in future to 'status' enum values with db table
        public bool IsComplete { get; set; }

        // Soft delete flag, can be extended to include 'DeletedAt' timestamp
        //
        // remarks: IsDeleted could be redundant as DeletedAt != null could imply deletion, IsDeleted is more explicit and can simplify queries
        // but for a small app and no code review done, we can keep it for now, risk the possibility of inconsistency
        public bool IsDeleted { get; set; } = false;

        // Track when it was deleted
        public DateTime? DeletedAt { get; set; }

        // Can be extended in future to 'User' model
        public string? AssignedTo { get; set; }

        // Can be extended in future to 'Priority' type with enum values with db table
        public string? Priority { get; set; }

        // Can be extended in future to 'Category' enum values with db table
        public string? Category { get; set; }

        // Foreign key to Checklist, can be null if not part of any checklist, is indexed for performance
        public int? ChecklistId { get; set; }

    }

    // Model for creating a new work item, id will be generated by the database, this is DTO (Data Transfer Object)
    public class CreateWorkItem : IIdentifiable
    {
        [Required]
        public int Id { get; set; }
        [Required]
        [StringLength(200, MinimumLength = 1)]
        public string? Name { get; set; }
        [StringLength(500)]
        public string? Description { get; set; }
        // Foreign key to Checklist, can be null if not part of any checklist, is indexed for performance
        public int? ChecklistId { get; set; }
    }
}
